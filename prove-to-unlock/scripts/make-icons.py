#!/usr/bin/env python3
"""Draw the app icons (padlock + check) with no dependencies beyond the standard library.

Outputs:
  apps/desktop/assets/icon.png         512x512 app icon (electron-builder converts it per OS)
  apps/desktop/src/main/icon.ts        base64 32x32 monochrome tray icon (template image on macOS)
  apps/extension/static/icons/*.png    16/32/48/128 extension icons
  apps/ios/ProveToUnlock/Assets.xcassets/AppIcon.appiconset/icon-1024.png
"""
import math
import os
import struct
import zlib

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def png(width, height, pixels):
    raw = b"".join(b"\x00" + bytes(pixels[y * width * 4:(y + 1) * width * 4]) for y in range(height))

    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def rounded_rect(x, y, x0, y0, x1, y1, r):
    cx = min(max(x, x0 + r), x1 - r)
    cy = min(max(y, y0 + r), y1 - r)
    return math.hypot(x - cx, y - cy) <= r


def seg_dist(px, py, ax, ay, bx, by):
    dx, dy = bx - ax, by - ay
    t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def shape(u, v):
    """Return (layer) at normalized coords u,v in [0,1]: 0 none, 1 lock body, 2 shackle, 3 check."""
    # check mark (drawn on top of the body)
    if seg_dist(u, v, 0.38, 0.66, 0.47, 0.75) < 0.035 or seg_dist(u, v, 0.47, 0.75, 0.64, 0.56) < 0.035:
        if rounded_rect(u, v, 0.26, 0.45, 0.74, 0.86, 0.06):
            return 3
    if rounded_rect(u, v, 0.26, 0.45, 0.74, 0.86, 0.06):
        return 1
    # shackle: an arch (ring segment) above the body
    d = math.hypot(u - 0.5, v - 0.45)
    if v <= 0.45 and 0.13 <= d <= 0.19:
        return 2
    if 0.45 < v < 0.5 and (abs(u - 0.34) < 0.03 or abs(u - 0.66) < 0.03):
        return 2
    return 0


def render(size, mode):
    ss = 4
    px = []
    for y in range(size):
        for x in range(size):
            acc = [0.0, 0.0, 0.0, 0.0]
            for sy in range(ss):
                for sx in range(ss):
                    u = (x + (sx + 0.5) / ss) / size
                    v = (y + (sy + 0.5) / ss) / size
                    if mode == "app":
                        if not rounded_rect(u, v, 0.04, 0.04, 0.96, 0.96, 0.2):
                            continue
                        t = v
                        bg = (int(70 + 40 * t), int(100 + 20 * t), int(255 - 60 * t))
                        layer = shape(u, v)
                        col = {0: bg, 1: (255, 255, 255), 2: (255, 255, 255), 3: (62, 207, 142)}[layer]
                        acc = [acc[0] + col[0], acc[1] + col[1], acc[2] + col[2], acc[3] + 255]
                    else:  # tray: black on transparent, check knocked out
                        layer = shape(u, v)
                        if layer in (1, 2):
                            acc = [acc[0], acc[1], acc[2], acc[3] + 255]
            n = ss * ss
            a = acc[3] / n
            if a > 0:
                px += [int(acc[0] / (acc[3] / 255)), int(acc[1] / (acc[3] / 255)), int(acc[2] / (acc[3] / 255)), int(a)]
            else:
                px += [0, 0, 0, 0]
    return png(size, size, px)


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    print("wrote", os.path.relpath(path, ROOT))


def main():
    write(os.path.join(ROOT, "apps/desktop/assets/icon.png"), render(512, "app"))
    tray = render(32, "tray")
    import base64

    write(
        os.path.join(ROOT, "apps/desktop/src/main/icon.ts"),
        ("// Generated by scripts/make-icons.py\nexport const TRAY_ICON_PNG_B64 =\n  \"%s\";\n" % base64.b64encode(tray).decode()).encode(),
    )
    for s in (16, 32, 48, 128):
        write(os.path.join(ROOT, f"apps/extension/static/icons/icon-{s}.png"), render(s, "app"))
    write(os.path.join(ROOT, "apps/ios/ProveToUnlock/Assets.xcassets/AppIcon.appiconset/icon-1024.png"), render(1024, "app"))


if __name__ == "__main__":
    main()
